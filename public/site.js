/* ---------- Find-your-ride quiz ---------- */
function initQuiz() {
  const quiz = $("#quiz");
  if (!quiz) return;
  const steps = $$(".quiz-step", quiz);
  const bars = $$(".quiz-progress span", quiz);
  const answers = {};
  let i = 0;

  function show(n) {
    i = n;
    steps.forEach((s, k) => s.classList.toggle("active", k === n));
    bars.forEach((b, k) => b.classList.toggle("done", k <= n));
    $(".quiz-result", quiz).classList.remove("active");
  }

  function score(b) {
    let s = 0;
    if (answers.exp === "new") { s += b.beginner ? 3 : -6; if (b.cc > 300) s -= 3; }
    if (answers.exp === "some") { s += b.cc >= 240 && b.cc <= 500 ? 2 : 0; }
    if (answers.exp === "pro") { s += b.cc >= 380 ? 3 : 0; }
    if (answers.use === b.style) s += 4;
    if (answers.use === "adventure" && b.clearance >= 250) s += 1;
    if (answers.height === "short") { s += b.seat <= 780 ? 3 : b.seat >= 820 ? -3 : 0; }
    if (answers.height === "tall") { s += b.seat >= 810 ? 2 : 0; }
    if (answers.priority === "cost") s += b.cc <= 260 ? 2 : 0;
    if (answers.priority === "tour") s += b.style === "adventure" && b.cc >= 290 ? 2 : 0;
    if (answers.priority === "looks") s += b.style !== "adventure" ? 1 : 0;
    if (b.featured) s += 0.5;
    return s;
  }

  function finish() {
    const ranked = [...BIKES].sort((a, b) => score(b) - score(a));
    const top = ranked[0], alt = ranked.slice(1, 3);
    track("quiz_complete", { result: top.id, answers });
    const res = $(".quiz-result", quiz);
    steps.forEach(s => s.classList.remove("active"));
    bars.forEach(b => b.classList.add("done"));
    res.innerHTML = `
      <div class="media"><img src="${bikeImg(top)}" srcset="${srcset(top.imgs[0])}" sizes="(max-width: 760px) 92vw, 520px" alt="${top.brand} ${top.name}" style="${top.photo ? "object-fit:cover" : ""}"></div>
      <div>
        <p class="kicker">Your match</p>
        <h3 style="font-size:clamp(2.2rem,5vw,3.4rem);text-transform:uppercase;font-variation-settings:'wdth' 64;margin-bottom:6px">${top.brand} ${top.name}</h3>
        <p>${top.tagline}</p>
        <div class="specs" style="display:flex;gap:6px;flex-wrap:wrap;margin-bottom:18px">
          <span class="chip">${top.cc} cc</span><span class="chip">Seat ${top.seat} mm</span><span class="chip">${top.weight} kg</span>
        </div>
        <div class="btn-row">
          <a class="btn btn-red" href="book.html?bike=${top.id}">Book a test ride</a>
          <a class="btn btn-ghost" href="${bikeUrl(top)}">See the bike</a>
        </div>
        <p class="also">Also worth a look: ${alt.map(b => `<a href="${bikeUrl(b)}">${b.brand} ${b.name}</a>`).join(" and ")}.</p>
        <button class="quiz-back" type="button" data-restart>Start again</button>
      </div>`;
    res.classList.add("active");
    imgFallback($("img", res));
    $("[data-restart]", res).addEventListener("click", () => show(0));
  }

  $$(".option", quiz).forEach(opt => opt.addEventListener("click", () => {
    answers[opt.dataset.q] = opt.dataset.v;
    if (i < steps.length - 1) show(i + 1); else finish();
  }));
  $$(".quiz-step .quiz-back", quiz).forEach(b => b.addEventListener("click", () => show(Math.max(0, i - 1))));
  show(0);
}

/* ---------- Finance calculator ---------- */
function initCalc(root = document) {
  const calc = $(".calc", root);
  if (!calc) return;
  const price = $("[data-calc-price]", calc);
  const dep = $("[data-calc-deposit]", calc);
  const depOut = $("[data-calc-deposit-out]", calc);
  let term = FIN.defaultTerm;

  const termWrap = $("[data-calc-terms]", calc);
  termWrap.innerHTML = FIN.terms.map(t => `<button type="button" data-term="${t}" aria-pressed="${t === term}">${t} mo</button>`).join("");
  $$("button", termWrap).forEach(b => b.addEventListener("click", () => {
    term = +b.dataset.term;
    $$("button", termWrap).forEach(x => x.setAttribute("aria-pressed", x === b));
    update();
  }));

  const bikeSel = $("[data-calc-bike]", calc);
  if (bikeSel) {
    bikeSel.innerHTML = BIKES.map(b => `<option value="${b.id}">${b.brand} ${b.name}</option>`).join("");
    const pre = new URLSearchParams(location.search).get("bike") || "tekken-250-evo";
    bikeSel.value = bikeById(pre) ? pre : "tekken-250-evo";
    bikeSel.addEventListener("change", () => {
      const b = bikeById(bikeSel.value);
      if (b.price) price.value = b.price;
      else { price.value = ""; price.placeholder = "Enter the price we quoted you"; }
      update();
    });
    const b0 = bikeById(bikeSel.value);
    if (b0.price) price.value = b0.price;
  }

  function update() {
    const p = Math.max(0, +price.value || 0);
    const d = +dep.value;
    depOut.textContent = d + "%";
    const r = monthlyFor(p, d, term);
    $("[data-out-monthly]", calc).textContent = p ? kes(r.monthly) : "KES —";
    $("[data-out-deposit]", calc).textContent = p ? kes(r.deposit) : "—";
    $("[data-out-loan]", calc).textContent = p ? kes(r.loan) : "—";
    $("[data-out-total]", calc).textContent = p ? kes(r.total) : "—";
    $("[data-out-term]", calc).textContent = term + " months";
    const apply = $("[data-calc-apply]", calc);
    if (apply) {
      const name = bikeSel ? (b => `${b.brand} ${b.name}`)(bikeById(bikeSel.value)) : (calc.dataset.bike || "a bike");
      apply.href = waLink(`Hi, I'd like to apply for financing on the ${name}. Deposit ${d}%, ${term} months.`);
      Object.assign(apply.dataset, { price: p, deposit: d, term, monthly: r.monthly, bikeName: name, bikeId: bikeSel ? bikeSel.value : (calc.dataset.bikeId || "") });
    }
  }
  dep.min = FIN.minDepositPct;
  let used = false;
  const touched = () => { if (!used) { used = true; track("calc_use", { bike: bikeSel ? bikeSel.value : calc.dataset.bikeId }); } };
  price.addEventListener("input", () => { touched(); update(); });
  dep.addEventListener("input", () => { touched(); update(); });
  termWrap.addEventListener("click", touched);
  update();
}

