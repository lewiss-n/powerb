function monthlyFor(price, depositPct = FIN.defaultDepositPct, months = FIN.defaultTerm) {
  const deposit = price * depositPct / 100;
  const loan = price - deposit;
  const interest = loan * FIN.monthlyFlatRate * months;
  return { deposit, loan, interest, monthly: (loan + interest) / months, total: deposit + loan + interest };
}

