  const date = $("#b-date");
  const today = new Date(Date.now() + 3 * 3600e3 + 864e5);
  date.min = today.toISOString().slice(0, 10);
  if (today.getUTCDay() === 0) today.setUTCDate(today.getUTCDate() + 1); // closed Sundays: default to Monday
