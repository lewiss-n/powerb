/* ---------- Live forms: parts, contact, newsletter, wall, RSVP, notify ---------- */
function bindForm(form, handler) {
  if (!form) return;
  form.addEventListener("submit", async e => {
    e.preventDefault();
    const out = $(".form-success", form), btn = $("button[type=submit]", form);
    btn.disabled = true;
    try {
      const html = await handler();
      if (out) { out.className = "form-success show"; out.innerHTML = html; } else btn.textContent = html;
      form.querySelectorAll("input:not([type=submit]), textarea").forEach(i => { i.value = ""; });
    } catch (err) {
      if (out) { out.className = "form-success show error"; out.textContent = err.message; } else { btn.textContent = "Try again"; alert(err.message); }
    }
    btn.disabled = false;
  });
}

